  await dialog.getByRole('button', { name: 'Guardar borrador' }).click();
  await page.getByRole('button', { name: 'Abrir Mesa 1, cambios pendientes' }).waitFor();
  assert.equal(saves, 0);
  await page.reload();
  await page.getByRole('button', { name: 'Punto de venta', exact: true }).click();
  await page.getByRole('button', { name: 'Abrir Mesa 1, cambios pendientes' }).click();
  await dialog.getByRole('button', { name: 'Continuar' }).click();
  await dialog.getByRole('button', { name: 'Editar borrador' }).click();
  await dialog.getByLabel('Cantidad', { exact: true }).fill('4');
  await dialog.getByRole('button', { name: 'Guardar borrador' }).click();
  await dialog.waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: 'Abrir Mesa 1, cambios pendientes' }).click();
  await dialog.getByRole('button', { name: 'Continuar' }).click();
  await dialog.getByRole('button', { name: 'Editar borrador' }).click();
  await dialog.getByLabel('Cantidad', { exact: true }).fill('3');
  await dialog.getByRole('button', { name: 'Guardar borrador' }).click();
  await page.getByRole('button', { name: 'Abrir Mesa 1, cambios pendientes' }).waitFor();
  online = true;
  await page.getByRole('button', { name: 'Resumen', exact: true }).click();
  await page.getByRole('button', { name: 'Punto de venta', exact: true }).click();
  await page.getByRole('button', { name: 'Abrir Mesa 1, cambios pendientes' }).click();
