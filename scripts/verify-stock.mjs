import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';

const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1366, height: 768 } });
try {
  await page.goto(process.env.BASE_URL || 'http://127.0.0.1:5198');
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  await page.getByRole('button', { name: 'Stock', exact: true }).click();
  await page.getByRole('heading', { name: 'Stock', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Controlar stock' }).first().click();
  const dialog = page.getByRole('dialog', { name: 'Flat white' });
  await dialog.getByRole('spinbutton', { name: 'Cantidad real', exact: true }).fill('2');
  await dialog.getByRole('spinbutton', { name: 'Avisar al llegar a', exact: true }).fill('1');
  await dialog.getByRole('button', { name: 'Guardar movimiento' }).click();
  assert.equal((await page.evaluate(() => JSON.parse(localStorage.getItem('carmela.inventory.v1'))))['1'].quantity, 2);
  await page.locator('.theme-toggle').click();
  await page.getByRole('button', { name: 'Carga rápida' }).click();
  const bulk = page.getByRole('dialog', { name: 'Carga rápida de stock' });
  await page.waitForTimeout(300);
  await page.screenshot({ path: 'artifacts/stock-bulk-dark.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'artifacts/stock-bulk-mobile.png' });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.setViewportSize({ width: 1366, height: 768 });
  await bulk.getByRole('spinbutton', { name: 'Cantidad real de Flat white' }).focus();
  await page.keyboard.press('Enter');
  assert.equal(await bulk.getByRole('spinbutton', { name: 'Cantidad real de Croissant de manteca' }).evaluate((element) => element === document.activeElement), true);
  await bulk.getByRole('spinbutton', { name: 'Cantidad real de Croissant de manteca' }).fill('4');
  await bulk.getByRole('spinbutton', { name: 'Mínimo de Croissant de manteca' }).fill('2');
  await bulk.getByRole('spinbutton', { name: 'Cantidad real de Avocado toast' }).fill('3');
  await bulk.getByRole('spinbutton', { name: 'Mínimo de Avocado toast' }).fill('1');
  await bulk.getByRole('button', { name: 'Guardar cambios' }).click();
  const stockAfterBulk = await page.evaluate(() => JSON.parse(localStorage.getItem('carmela.inventory.v1')));
  assert.equal(stockAfterBulk['1'].quantity, 2);
  assert.equal(stockAfterBulk['2'].quantity, 4);
  assert.equal(stockAfterBulk['3'].minimum, 1);

  await page.getByRole('button', { name: 'Punto de venta', exact: true }).click();
  await page.getByRole('button', { name: /Abrir Mesa 1, libre/ }).first().click();
  await page.getByRole('button', { name: 'Trabajar como Camila López' }).click();
  await page.locator('.covers-modal').getByRole('button', { name: 'Abrir mesa', exact: true }).click();
  const account = page.getByRole('dialog', { name: 'Cuenta de Mesa 1' });
  await account.getByRole('button', { name: 'Agregar Flat white', exact: true }).click();
  await account.getByRole('button', { name: /Cobrar y cerrar/ }).click();
  await page.getByRole('dialog', { name: /Cobrar Mesa 1/ }).getByRole('radio', { name: 'Efectivo' }).check();
  await page.getByRole('button', { name: /Confirmar cobro/ }).click();
  const pin = page.getByRole('dialog', { name: /Código de Camila López/ });
  if (await pin.count()) {
    await pin.getByRole('textbox', { name: /Código de Camila López/ }).fill('4829');
    await pin.getByRole('button', { name: /Confirmar cobro/ }).click();
  }
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('carmela.inventory.v1'))?.['1']?.quantity === 1);
  assert.equal((await page.evaluate(() => JSON.parse(localStorage.getItem('carmela.inventory.v1'))))['1'].quantity, 1);
  await page.getByRole('button', { name: 'Notificaciones: 1 producto con stock bajo' }).click();
  const alerts = page.getByRole('region', { name: 'Notificaciones de stock' });
  await alerts.getByText('Flat white').waitFor();
  await page.waitForTimeout(350);
  await page.screenshot({ path: 'artifacts/stock-alert.png' });
  await alerts.getByRole('button', { name: /Flat white/ }).click();
  await page.getByRole('heading', { name: 'Stock', exact: true }).waitFor();
  await page.getByRole('button', { name: /Para reponer/ }).click();
  assert.equal(await page.locator('.stock-row').count(), 1);
  await page.reload();
  await page.getByRole('button', { name: 'Stock', exact: true }).click();
  assert.equal((await page.evaluate(() => JSON.parse(localStorage.getItem('carmela.inventory.v1'))))['1'].quantity, 1);
  assert.ok((await page.evaluate(() => JSON.parse(localStorage.getItem('carmela.inventory.movements.v1')))).some((movement) => movement.type === 'venta'));
  await page.waitForTimeout(350);
  await page.screenshot({ path: 'artifacts/stock-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(350);
  await page.screenshot({ path: 'artifacts/stock-mobile.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.setViewportSize({ width: 1366, height: 768 });
  await page.getByRole('button', { name: 'Ajustar stock de Flat white' }).click();
  await page.getByRole('dialog', { name: 'Flat white' }).getByRole('spinbutton', { name: 'Cantidad real', exact: true }).fill('0');
  await page.getByRole('button', { name: 'Guardar movimiento' }).click();
  await page.getByRole('button', { name: 'Punto de venta', exact: true }).click();
  await page.getByRole('button', { name: /Abrir Mesa 1, libre/ }).first().click();
  await page.getByRole('button', { name: 'Trabajar como Camila López' }).click();
  await page.locator('.covers-modal').getByRole('button', { name: 'Abrir mesa', exact: true }).click();
  assert.equal(await page.getByRole('dialog', { name: 'Cuenta de Mesa 1' }).getByRole('button', { name: 'Agregar Flat white', exact: true }).count(), 0);
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Stock', exact: true }).click();
  await page.getByRole('button', { name: 'Ingresar unidades de Flat white' }).click();
  await page.getByRole('dialog', { name: 'Flat white' }).getByRole('spinbutton', { name: 'Unidades', exact: true }).fill('3');
  await page.getByRole('button', { name: 'Guardar movimiento' }).click();
  await page.getByRole('button', { name: 'Notificaciones: sin alertas de stock' }).click();
  await page.getByText('No hay productos con stock bajo.').waitFor();
  console.log('PASS: stock, sale decrement, alert lifecycle, persistence and mobile layout');
} finally { await browser.close(); }
