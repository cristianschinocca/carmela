import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';
import { enableDemoSession } from './demo-session.mjs';

const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1366, height: 768 } });
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
await enableDemoSession(page);
try {
  await page.goto(process.env.BASE_URL || 'http://127.0.0.1:5198');
  await page.getByRole('button', { name: 'Stock', exact: true }).click();
  const section = (name) => page.getByRole('navigation', { name: 'Secciones de stock' }).getByRole('button', { name, exact: true });
  await section('Proveedores').click();
  for (const name of ['Distribuidora Norte', 'Café del Sur']) {
    await page.getByRole('button', { name: 'Nuevo proveedor' }).click();
    const dialog = page.getByRole('dialog', { name: 'Nuevo proveedor' });
    await dialog.getByLabel('Nombre', { exact: true }).fill(name);
    await dialog.getByLabel('Teléfono').fill('1123456789');
    await dialog.getByRole('button', { name: 'Guardar proveedor' }).click();
  }
  await section('Insumos').click();
  await page.getByRole('button', { name: 'Nuevo insumo' }).click();
  let dialog = page.getByRole('dialog', { name: 'Nuevo insumo' });
  await dialog.getByLabel('Nombre', { exact: true }).fill('Café en grano');
  await dialog.getByLabel('Unidad', { exact: true }).selectOption('g');
  await dialog.getByLabel('Cantidad actual').fill('500.5');
  await dialog.getByLabel('Stock mínimo').fill('600');
  await dialog.getByLabel('Distribuidora Norte').check();
  await dialog.getByLabel('Café del Sur').check();
  await dialog.getByRole('button', { name: 'Guardar insumo' }).click();
  assert.equal(await page.getByText(/Reponer/).count(), 1);
  await section('Recetas').click();
  await page.getByRole('button', { name: 'Nueva receta' }).click();
  dialog = page.getByRole('dialog', { name: 'Nueva receta' });
  await dialog.getByLabel('Nombre de la receta').fill('Espresso doble');
  await dialog.getByLabel('Producto del POS').selectOption({ label: 'Flat white · Café' });
  await dialog.getByLabel('Insumo 1', { exact: true }).selectOption({ label: 'Café en grano (g)' });
  await dialog.getByLabel('Cantidad', { exact: true }).fill('18');
  await dialog.getByRole('button', { name: 'Guardar receta' }).click();
  await page.reload();
  await page.getByRole('button', { name: 'Stock', exact: true }).click();
  await section('Recetas').click();
  assert.equal(await page.getByText('Espresso doble', { exact: true }).count(), 1);
  assert.match(await page.locator('body').innerText(), /18 g Café en grano/);
  await section('Insumos').click();
  await page.getByRole('button', { name: 'Eliminar Café en grano' }).click();
  assert.equal(await page.getByText('Café en grano', { exact: true }).count(), 1);
  await page.getByRole('button', { name: 'Editar Café en grano' }).click();
  dialog = page.getByRole('dialog', { name: 'Editar insumo' });
  assert.equal(await dialog.getByLabel('Unidad', { exact: true }).isDisabled(), true);
  assert.equal(await dialog.getByLabel('Distribuidora Norte').isChecked(), true);
  assert.equal(await dialog.getByLabel('Café del Sur').isChecked(), true);
  await dialog.getByLabel('Cantidad actual').fill('750');
  await dialog.getByRole('button', { name: 'Guardar insumo' }).click();
  await section('Proveedores').click();
  await page.getByRole('button', { name: 'Eliminar Distribuidora Norte' }).click();
  assert.equal(await page.getByText('Distribuidora Norte', { exact: true }).count(), 1);
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('carmela.stock.catalog.v1')));
  assert.equal(saved.ingredients[0].quantity, 750);
  assert.equal(saved.ingredients[0].supplierIds.length, 2);
  assert.equal(saved.recipes[0].productId, 1);
  await page.locator('.theme-toggle').click();
  await page.setViewportSize({ width: 390, height: 844 });
  await section('Recetas').click();
  await page.getByRole('button', { name: 'Editar Espresso doble' }).click();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('dialog').count(), 0);
  await page.setViewportSize({ width: 1366, height: 768 });
  await page.getByRole('button', { name: 'Editar Espresso doble' }).click();
  dialog = page.getByRole('dialog', { name: 'Editar receta' });
  await dialog.getByLabel('Cantidad', { exact: true }).fill('20');
  await dialog.getByRole('button', { name: 'Guardar receta' }).click();
  assert.match(await page.locator('body').innerText(), /20 g Café en grano/);
  await page.getByRole('button', { name: 'Nueva receta' }).click();
  dialog = page.getByRole('dialog', { name: 'Nueva receta' });
  await dialog.getByLabel('Nombre de la receta').fill('Duplicada');
  await dialog.getByLabel('Producto del POS').selectOption({ label: 'Flat white · Café' });
  await dialog.getByLabel('Insumo 1').selectOption({ label: 'Café en grano (g)' });
  await dialog.getByLabel('Cantidad', { exact: true }).fill('1');
  await dialog.getByRole('button', { name: 'Guardar receta' }).click();
  assert.equal(await dialog.getByRole('alert').innerText(), 'Este producto ya tiene una receta.');
  await page.keyboard.press('Escape');
  page.once('dialog', (confirm) => confirm.accept());
  await page.getByRole('button', { name: 'Eliminar Espresso doble' }).click();
  await page.getByText('Todavía no creaste recetas.').waitFor();
  await section('Insumos').click();
  page.once('dialog', (confirm) => confirm.accept());
  await page.getByRole('button', { name: 'Eliminar Café en grano' }).click();
  await page.getByText('Agregá tu primer insumo para comenzar a crear recetas.').waitFor();
  assert.deepEqual(errors, []);
  console.log('PASS: proveedores, insumos, receta vinculada al POS, persistencia y relaciones.');
} finally { await browser.close(); }
