import { chromium } from "@playwright/test";

const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const base = process.env.BASE_URL || "http://127.0.0.1:5198";

try {
  await page.goto(base);
  await page.getByRole("button", { name: "Equipo", exact: true }).click();
  await page.evaluate(() => document.documentElement.setAttribute("data-theme", "dark"));
  await page.getByRole("button", { name: "Nuevo empleado" }).click();
  let editor = page.getByRole("dialog", { name: "Nuevo empleado" });
  await editor.getByLabel("Nombre completo").fill("Prueba Sueldo");
  await editor.getByLabel("Código de fichaje").fill("9876");
  await editor.getByRole("button", { name: /Jornada semanal/ }).click();
  let schedule = page.getByRole("dialog", { name: "Jornada semanal" });
  for (const day of ["Lun", "Mar", "Mié", "Jue", "Vie"]) await schedule.getByRole("button", { name: day, exact: true }).click();
  await schedule.getByLabel("Entrada Mar").fill("10:00");
  await schedule.getByLabel("Salida Mar").fill("14:00");
  await schedule.getByRole("button", { name: "Aplicar cambios" }).click();
  editor = page.getByRole("dialog", { name: "Nuevo empleado" });
  await editor.getByRole("button", { name: /Tarifa de pago/ }).click();
  let rate = page.getByRole("dialog", { name: "Tarifa de pago" });
  await rate.getByRole("button", { name: "Aplicar cambios" }).click();
  await rate.getByText("Ingresá un importe mayor a cero.").waitFor();
  await rate.getByLabel("Importe ($)").fill("1000");
  const now = new Date();
  let days = 0, tuesdays = 0;
  for (let day = 1; day <= new Date(now.getFullYear(), now.getMonth() + 1, 0).getDate(); day++) {
    const weekday = new Date(now.getFullYear(), now.getMonth(), day).getDay();
    if ([1, 2, 3, 4, 5].includes(weekday)) days++;
    if (weekday === 2) tuesdays++;
  }
  const expected = `$ ${new Intl.NumberFormat("es-AR").format((days * 8 - tuesdays * 4) * 1000)}`;
  if ((await rate.locator(".team-setup-estimate strong").innerText()) !== expected) throw new Error("Hourly estimate is incorrect");
  await rate.getByRole("button", { name: "Aplicar cambios" }).click();
  editor = page.getByRole("dialog", { name: "Nuevo empleado" });
  await editor.getByRole("button", { name: /Tarifa de pago/ }).click();
  rate = page.getByRole("dialog", { name: "Tarifa de pago" });
  await rate.getByLabel("Importe ($)").fill("9999");
  await rate.getByRole("button", { name: "Cancelar" }).click();
  editor = page.getByRole("dialog", { name: "Nuevo empleado" });
  if (!(await editor.innerText()).includes(expected)) throw new Error("Cancel changed the draft");
  await editor.getByRole("button", { name: "Crear empleado" }).click();
  await page.getByText("Prueba Sueldo").waitFor();
  await page.reload();
  await page.getByRole("button", { name: "Equipo", exact: true }).click();
  if (!(await page.locator(".team-list").innerText()).includes(expected)) throw new Error("Monthly estimate did not persist");
  await page.getByRole("button", { name: "Editar Prueba Sueldo" }).click();
  editor = page.getByRole("dialog", { name: "Editar empleado" });
  await page.setViewportSize({ width: 1366, height: 768 });
  await page.waitForTimeout(300);
  if (await editor.locator(".member-form-body").evaluate((element) => element.scrollHeight > element.clientHeight + 1)) throw new Error("Employee editor scrolls at desktop size");
  await page.screenshot({ path: "artifacts/team-employee-editor.png" });
  await editor.getByRole("button", { name: /Jornada semanal/ }).click();
  schedule = page.getByRole("dialog", { name: "Jornada semanal" });
  if (await schedule.getByLabel("Entrada Mar").inputValue() !== "10:00" || await schedule.getByLabel("Salida Mar").inputValue() !== "14:00") throw new Error("Schedule did not persist");
  await page.waitForTimeout(300);
  await page.screenshot({ path: "artifacts/team-schedule-editor.png" });
  await schedule.getByLabel("Salida Mar").fill("09:00");
  await schedule.getByRole("button", { name: "Aplicar cambios" }).click();
  await schedule.getByRole("alert").waitFor();
  await page.keyboard.press("Escape");
  editor = page.getByRole("dialog", { name: "Editar empleado" });
  await editor.getByRole("button", { name: /Tarifa de pago/ }).click();
  rate = page.getByRole("dialog", { name: "Tarifa de pago" });
  await rate.getByLabel("Tipo de pago").selectOption("day");
  await rate.getByLabel("Importe ($)").fill("20000");
  const dailyExpected = `$ ${new Intl.NumberFormat("es-AR").format(days * 20000)}`;
  if ((await rate.locator(".team-setup-estimate strong").innerText()) !== dailyExpected) throw new Error("Daily estimate is incorrect");
  await rate.getByRole("button", { name: "Aplicar cambios" }).click();
  await page.getByRole("dialog", { name: "Editar empleado" }).getByRole("button", { name: "Guardar cambios" }).click();
  if (!(await page.locator(".team-list").innerText()).includes(dailyExpected)) throw new Error("Daily rate did not persist");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "Editar Prueba Sueldo" }).click();
  const mobileEditor = page.getByRole("dialog", { name: "Editar empleado" });
  await page.waitForTimeout(300);
  if (await mobileEditor.locator(".member-form-body").evaluate((element) => element.scrollHeight > element.clientHeight + 1)) throw new Error("Employee editor scrolls at mobile size");
  await page.screenshot({ path: "artifacts/team-employee-mobile.png" });
  await mobileEditor.getByRole("button", { name: /Jornada semanal/ }).click();
  await page.waitForTimeout(300);
  await page.screenshot({ path: "artifacts/team-schedule-mobile.png" });
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error("Mobile width overflows");
  console.log("PASS: separate dialogs, schedule and pay calculations, cancel, persistence and mobile layout.");
} finally {
  await browser.close();
}
