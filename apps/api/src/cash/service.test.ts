import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { after, test } from 'node:test';
import { closeDatabases, tenantDatabase } from '@mistro/db/tenant';
import { cashOperation, parseCashOperation, readCash } from './service.js';
const key = process.env.CASH_TEST_DB_KEY;
test('valida importes, movimientos y fechas', () => {
  assert.equal(parseCashOperation({ id: randomUUID(), action: 'open', openingAmount: -1 }), null);
  assert.equal(parseCashOperation({ id: randomUUID(), action: 'open', openingAmount: 1.5 }), null);
  assert.equal(parseCashOperation({ id: randomUUID(), action: 'record', shiftId: randomUUID(), expectedVersion: 0, movementId: randomUUID(), movement: { kind: 'retiro', direction: 'in', amount: 100, payment: 'Efectivo', concept: 'Retiro', party: 'Caja', receipt: '' } }), null);
});
test('caja conserva movimientos, controla concurrencia y repite operaciones sin duplicarlas', { skip: !key }, async () => {
  const db = tenantDatabase(key!);
  const open = parseCashOperation({ id: randomUUID(), action: 'open', openingAmount: 10000 })!;
  const opened = await cashOperation(db, 'owner', open);
  assert.equal((await cashOperation(db, 'owner', open)).replayed, true);
  const id = randomUUID();
  const movement = { kind: 'gasto', direction: 'out', amount: 2000, payment: 'Efectivo', concept: 'Café', party: '', receipt: '' };
  const record = parseCashOperation({ id: randomUUID(), action: 'record', shiftId: opened.shiftId, expectedVersion: 0, movementId: id, movement })!;
  await cashOperation(db, 'owner', record);
  assert.equal((await cashOperation(db, 'owner', record)).replayed, true);
  assert.equal((await readCash(db))?.expectedAmount, '8000');
  const stale = parseCashOperation({ id: randomUUID(), action: 'void', shiftId: opened.shiftId, expectedVersion: 0, movementId: id, movementVersion: 0 })!;
  await assert.rejects(() => cashOperation(db, 'owner', stale));
  const edit = parseCashOperation({ id: randomUUID(), action: 'edit', shiftId: opened.shiftId, expectedVersion: 1, movementId: id, movementVersion: 0, movement: { ...movement, amount: 3000 } })!;
  await cashOperation(db, 'owner', edit);
  assert.equal((await readCash(db))?.expectedAmount, '7000');
  const voided = parseCashOperation({ id: randomUUID(), action: 'void', shiftId: opened.shiftId, expectedVersion: 2, movementId: id, movementVersion: 1 })!;
  await cashOperation(db, 'owner', voided);
  assert.equal((await readCash(db))?.expectedAmount, '10000');
  assert.equal((await db.cashOperation.findMany()).length, 4);
  const noReason = parseCashOperation({ id: randomUUID(), action: 'close', shiftId: opened.shiftId, expectedVersion: 3, countedAmount: 7000, differenceReason: '' })!;
  await assert.rejects(() => cashOperation(db, 'owner', noReason));
  const close = parseCashOperation({ ...noReason, id: randomUUID(), differenceReason: 'Diferencia de conteo' })!;
  await cashOperation(db, 'owner', close);
  assert.equal(await readCash(db), null);
  const stored = await db.cashShift.findUniqueOrThrow({ where: { id: opened.shiftId } });
  assert.equal(stored.expectedAmount, 10000n); assert.equal(stored.countedAmount, 7000n);
});
after(async () => { await closeDatabases(); });
